const KAKAO_URL = "https://open.kakao.com/o/snG6VXti";
const BUSINESS_CARD_LINK_URL = "tel:01054881456";

function parseFileName(filename) {
  if (!filename.endsWith(".html")) return null;
  const withoutExt = filename.slice(0, -5);
  const idx = withoutExt.indexOf("_");
  if (idx === -1) return null;
  return { slug: withoutExt.slice(0, idx), title: withoutExt.slice(idx + 1) };
}

function collectManuscripts() {
  const items = [];
  for (const dateName of readdirSync(OUTPUT_DIR)) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(dateName)) continue;
    const dateDir = join(OUTPUT_DIR, dateName);
    if (!statSync(dateDir).isDirectory()) continue;

    for (const agencySlug of readdirSync(dateDir)) {
      if (!AGENCIES[agencySlug]) continue;
      const agencyDir = join(dateDir, agencySlug);
      if (!statSync(agencyDir).isDirectory()) continue;

      for (const file of readdirSync(agencyDir)) {
        const parsed = parseFileName(file);
        if (!parsed) continue;
        const html = readFileSync(join(agencyDir, file), "utf8");
        items.push({
          path: `${dateName}/${agencySlug}/${file}`,
          agency: agencySlug,
          slug: parsed.slug,
          title: parsed.title,
          date: dateName,
          html,
        });
      }
    }
  }
  // 최신 날짜가 위로
  items.sort((a, b) => (a.date === b.date ? a.slug.localeCompare(b.slug) : b.date.localeCompare(a.date)));
  return items;
}

function build() {
  const manuscripts = collectManuscripts();
  const generatedAt = new Date().toISOString();
  const data = {
    generatedAt,
    kakaoUrl: KAKAO_URL,
    businessCardLinkUrl: BUSINESS_CARD_LINK_URL,
    agencies: AGENCIES,
    manuscripts,
  };

  // 큰 HTML 콘텐츠가 들어가므로 JSON.stringify로 직렬화하고
  // 단일 전역 window.MIH 에 노출. 모아보기는 이 객체만 읽는다.
  const content =
    "// AUTO-GENERATED by scripts/build-manifest.js — DO NOT EDIT BY HAND\n" +
    "window.MIH = " +
    JSON.stringify(data, null, 2) +
    ";\n";

  writeFileSync(MANIFEST_PATH, content, "utf8");
  const manifestVersion = Date.parse(generatedAt);
  for (const htmlPath of HTML_WITH_MANIFEST_PATHS) {
    const html = readFileSync(htmlPath, "utf8");
    const updatedHtml = html.replace(
      /<script src="manifest\.js(?:\?v=\d+)?"><\/script>/,
      `<script src="manifest.js?v=${manifestVersion}"></script>`
    );
    if (updatedHtml !== html) {
      writeFileSync(htmlPath, updatedHtml, "utf8");
      console.log(`Updated ${htmlPath}`);
    }
  }
  console.log(`Wrote ${MANIFEST_PATH}`);
  console.log(`  manuscripts: ${manuscripts.length}`);
  for (const slug of Object.keys(AGENCIES)) {
    const n = manuscripts.filter((m) => m.agency === slug).length;
    console.log(`    ${slug}: ${n}`);
  }
}

build();
