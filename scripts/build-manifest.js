// output/ 폴더를 스캔해서 output/manifest.js를 만든다.
// manifest.js는 모아보기 페이지(output/index.html)가 읽는 단일 데이터 소스.
//
// 실행: npm run build
// 새 원고를 추가하거나 수정한 뒤 한 번 실행하면 모아보기에 반영된다.

import { readdirSync, statSync, readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dir = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dir, "..");
const OUTPUT_DIR = join(ROOT, "output");
const MANIFEST_PATH = join(OUTPUT_DIR, "manifest.js");
const HTML_WITH_MANIFEST_PATHS = [
  join(OUTPUT_DIR, "index.html"),
  join(OUTPUT_DIR, "keywords.html"),
];

