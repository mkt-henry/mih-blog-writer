/** CatNo → category 역인덱스. */
const CAT_OF = new Map();
for (const [category, nos] of Object.entries(GROUPS)) {
  for (const n of nos) CAT_OF.set(n, category);
}

/** `강연자` 는 gdfdhzgfgfhgdj(내부 슬러그 mih_speaker) 로 고정되고,
 *  나머지 공연 분류는 4계정에 분산된다(그 계정도 2026-09-07 부로 일반 섭외 대상). */
export const SPEAKER_CATEGORY = '강연자';
export const ENTERTAINER_CATEGORIES = [
  '가수', '방송인', '개그맨', '댄스', '퍼포먼스', '클래식', '전통', '기획공연', '외국인공연',
];

/** 공연 분류를 라운드로빈으로 나눠 갖는 계정. 크롤러(crawl-artsro-keywords)와
 *  백필(assign-keyword-agency)이 같은 목록을 써야 계정별 후보 풀이 어긋나지 않는다.
 *  2026-09-07: mih_speaker(표시 이름 influence)가 일반 섭외 계정이 되어 3계정 → 4계정. */
export const ENTERTAINER_ACCOUNTS = ['mih_casting', 'mih_agency', 'other', 'mih_speaker'];

export const ALL_CAT_NOS = Object.values(GROUPS).flat().filter((n) => n in LABELS);

/** CatNo 로 굵은 분류와 세부 장르를 얻는다. 모르는 CatNo 는 category=null 로 돌려준다. */
export function classifyCatNo(catNo) {
  const n = Number(catNo);
  const category = CAT_OF.get(n) ?? null;
  return {
    category,
    label: LABELS[n] ?? null,
    agency: category === SPEAKER_CATEGORY ? 'mih_speaker' : null,
    split: category !== SPEAKER_CATEGORY && category !== null,
  };
}

/** keywords.source URL 에서 CatNo 를 뽑는다. 없으면 null. */
export function catNoFromSource(source) {
  const m = /[?&]CatNo=(\d+)/.exec(source ?? '');
  return m ? Number(m[1]) : null;
}

/** keywords 행에서 세부 장르 라벨을 얻는다(원고 체인이 인물 성격을 판단할 때 쓴다). */
export function genreOfKeyword(row) {
  const n = catNoFromSource(row?.source);
  return n === null ? null : (LABELS[n] ?? null);
}
